async def register_media():
    now = datetime.now(timezone.utc)
    inserted = 0
    updated = 0

    print("Registering Media Studio catalog...")
    for item in MEDIA_SEED_DATA:
        doc = {
            **item,
            "created_at": now,
            "updated_at": now,
            "created_by": "system_phase7_1@bigchamp.in",
        }
        res = await db.media.update_one(
            {"media_id": item["media_id"]},
            {"$set": doc},
            upsert=True,
        )
        if res.upserted_id:
            inserted += 1
        else:
            updated += 1
        print(f" -> [{item['media_type'].upper()}] {item['display_name']} ({item['media_id']})")

    count = await db.media.count_documents({})
    print(f"\nCompleted! Total media documents in db.media: {count} (Inserted: {inserted}, Updated: {updated})")

if __name__ == "__main__":
    asyncio.run(register_media())
